const sessionCookie = "avian_session"
const csrfCookie = "avian_csrf"

// The deployment build sets this to its source commit, exposed for verification.
var buildRevision = "development"

type navigationLink struct{ Label, URL string }

var navigation = []navigationLink{{"Home", "/"}, {"Feed", "/feed"}, {"Species", "/species"}, {"Flocks", "/flocks"}, {"Search", "/search"}}

type pageData struct {
	Title, Active, CSRF, Tab, Next, Error, Email, Username, Message string
	Current                                                         *Member
	Profile                                                         *Member
	Navigation                                                      []navigationLink
	Species                                                         []Species
	Chirps                                                          []ChirpPreview
}

type application struct {
	store         *Store
	pages         *template.Template
	secret        []byte
	secureCookies bool
}

func newServer(store *Store) (*echo.Echo, error) {
	pages, err := template.ParseFS(templateFiles, "templates/*.html")
	if err != nil {
		return nil, fmt.Errorf("parse templates: %w", err)
	}
	secret := os.Getenv("SESSION_SECRET")
	if secret == "" {
		// Tests can construct a server without writing configuration. main requires
		// a persistent secret, generated by start.sh or setup-ec2.sh.
		secret, err = randomToken()
		if err != nil {
			return nil, err
		}
	}
	a := &application{store: store, pages: pages, secret: []byte(secret), secureCookies: os.Getenv("COOKIE_SECURE") == "true"}
	e := echo.New()
	e.HideBanner = true
	e.Use(a.protect)
	e.Static("/static", "static")
	e.HTTPErrorHandler = func(err error, c echo.Context) {
		if c.Response().Committed {
			return
		}
		code, message := http.StatusInternalServerError, "Something went wrong. Please try again."
		var httpError *echo.HTTPError
		if errors.As(err, &httpError) {
			code = httpError.Code
			message = fmt.Sprint(httpError.Message)
		}
		if code >= 500 {
			e.Logger.Error(err)
		}
		if renderErr := a.render(c, code, "message.html", pageData{Title: http.StatusText(code), Message: message}); renderErr != nil {
			e.Logger.Error(renderErr)
		}
	}
	e.GET("/", a.home)
	e.GET("/login", a.loginPage)
	e.POST("/login", a.login)
	e.POST("/register", a.register)
	e.POST("/logout", a.logout)
	e.GET("/me", func(c echo.Context) error {
		member := currentMember(c)
		if member == nil {
			return loginRedirect(c)
		}
		return c.Redirect(http.StatusSeeOther, fmt.Sprintf("/members/%d", member.ID))
	})
	e.GET("/members/:id", a.profile)
	e.GET("/species", func(c echo.Context) error {
		species, err := store.Species(c.Request().Context())
		if err != nil {
			return err
		}
		return a.render(c, http.StatusOK, "species.html", pageData{Title: "Species", Active: "/species", Species: species})
	})
	// Every planned destination has a shared shell now. Later checkpoints add
	// editing, search, feeds, and group behavior; these do not claim those features.
	for _, route := range []struct {
		path, title, message string
		protected            bool
	}{
		{"/feed", "Your birding community", "Chirps from the community will gather here. In the meantime, explore the birds in our catalog.", false},
		{"/flocks", "Find your flock", "A shared interest. A favorite patch of woodland. A new birding companion. Flock discovery is coming soon.", false},
		{"/flocks/new", "Start a flock", "Your next birding group starts here. Flock creation is coming soon.", true},
		{"/flocks/:id", "Flock", "Flock pages are coming soon. Explore our species catalog while the community takes shape.", false},
		{"/chirps/form", "Write a chirp", "A flash of color, a familiar call, a bird you have never seen before. You will soon be able to record it here.", true},
		{"/search", "Explore observations", "Search for birds and observations across the community. Observation search is coming soon.", false},
	} {
		route := route
		e.GET(route.path, func(c echo.Context) error {
			if route.protected && currentMember(c) == nil {
				return loginRedirect(c)
			}
			active := route.path
			if strings.HasPrefix(active, "/flocks") {
				active = "/flocks"
			}
			return a.render(c, http.StatusOK, "message.html", pageData{Title: route.title, Active: active, Message: route.message})
		})
	}
	e.GET("/api/health", func(c echo.Context) error {
		if err := store.Ping(c.Request().Context()); err != nil {
			return err
		}
		c.Response().Header().Set("X-Avian-Revision", buildRevision)
		return c.NoContent(http.StatusOK)
	})
	return e, nil
}

func currentMember(c echo.Context) *Member {
	member, _ := c.Get("member").(*Member)
	return member
}

func (a *application) render(c echo.Context, status int, name string, data pageData) error {
	data.Current = currentMember(c)
	data.CSRF, _ = c.Get("csrf").(string)
	data.Navigation = navigation
	var output bytes.Buffer
	if err := a.pages.ExecuteTemplate(&output, name, data); err != nil {
		return err
	}
	return c.HTMLBlob(status, output.Bytes())
}

func (a *application) setCookie(c echo.Context, name, value string, lifetime time.Duration) {
	c.SetCookie(&http.Cookie{Name: name, Value: value, Path: "/", HttpOnly: true, Secure: a.secureCookies,
		SameSite: http.SameSiteLaxMode, MaxAge: int(lifetime.Seconds()), Expires: time.Now().UTC().Add(lifetime)})
}

func (a *application) signature(value string) string {
	mac := hmac.New(sha256.New, a.secret)
	mac.Write([]byte(value))
	return hex.EncodeToString(mac.Sum(nil))
}

func (a *application) validGuestCSRF(value string) bool {
	token, signature, ok := strings.Cut(value, ".")
	return ok && len(token) == 64 && hmac.Equal([]byte(signature), []byte(a.signature(token)))
}

// CSRF is checked before any state-changing handler, including login and
// registration. Guest tokens are signed; signed-in tokens belong to the session.
func (a *application) protect(next echo.HandlerFunc) echo.HandlerFunc {
	return func(c echo.Context) error {
		c.Response().Header().Set("X-Content-Type-Options", "nosniff")
		c.Response().Header().Set("Referrer-Policy", "strict-origin-when-cross-origin")
		c.Response().Header().Set("Content-Security-Policy", "default-src 'self'; img-src 'self'; style-src 'self'; script-src 'self'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'")
		if strings.HasPrefix(c.Request().URL.Path, "/static/") || c.Request().URL.Path == "/api/health" {
			return next(c)
		}
		c.Request().Body = http.MaxBytesReader(c.Response(), c.Request().Body, 64<<10)
		c.Response().Header().Set("Cache-Control", "no-store")
		csrf := ""
		if cookie, err := c.Cookie(sessionCookie); err == nil {
			session, err := a.store.Session(c.Request().Context(), cookie.Value)
			if err == nil {
				c.Set("member", &session.Member)
				csrf = session.CSRF
			} else if errors.Is(err, sql.ErrNoRows) {
				a.setCookie(c, sessionCookie, "", -time.Hour)
			} else {
				return err
			}
		}
		if csrf == "" {
			if cookie, err := c.Cookie(csrfCookie); err == nil && a.validGuestCSRF(cookie.Value) {
				csrf = cookie.Value
			}
		}
		unsafe := c.Request().Method != http.MethodGet && c.Request().Method != http.MethodHead && c.Request().Method != http.MethodOptions
		if unsafe {
			if err := c.Request().ParseForm(); err != nil {
				return echo.NewHTTPError(http.StatusBadRequest, "The form could not be read. Please reload and try again.")
			}
			submitted := c.Request().PostForm.Get("csrf_token")
			if csrf == "" || subtle.ConstantTimeCompare([]byte(csrf), []byte(submitted)) != 1 {
				return echo.NewHTTPError(http.StatusForbidden, "This form expired or could not be verified. Reload the page and try again.")
			}
		}
		if csrf == "" {
			token, err := randomToken()
			if err != nil {
				return err
			}
			csrf = token + "." + a.signature(token)
			a.setCookie(c, csrfCookie, csrf, sessionLifetime)
		}
		c.Set("csrf", csrf)
		return next(c)
	}
}

func safeNext(raw string) string {
	parsed, err := url.Parse(raw)
	if err != nil || !strings.HasPrefix(raw, "/") || strings.HasPrefix(raw, "//") || parsed.IsAbs() || parsed.Host != "" || strings.ContainsAny(raw, "\\\r\n") || strings.ContainsAny(parsed.Path, "\\\r\n") || strings.HasPrefix(parsed.Path, "//") {
		return "/feed"
	}
	if parsed.Path == "/login" || parsed.Path == "/register" || parsed.Path == "/logout" {
		return "/feed"
	}
	return raw
}

func loginRedirect(c echo.Context) error {
	return c.Redirect(http.StatusSeeOther, "/login?next="+url.QueryEscape(c.Request().URL.RequestURI()))
}

func (a *application) home(c echo.Context) error {
	species, err := a.store.Species(c.Request().Context())
	if err != nil {
		return err
	}
	if len(species) > 3 {
		species = species[:3]
	}
	chirps, err := a.store.RecentPublicChirps(c.Request().Context())
	if err != nil {
		return err
	}
	return a.render(c, http.StatusOK, "home.html", pageData{Title: "Birdwatching together", Active: "/", Species: species, Chirps: chirps})
}

func (a *application) loginPage(c echo.Context) error {
	next := safeNext(c.QueryParam("next"))
	if currentMember(c) != nil {
		return c.Redirect(http.StatusSeeOther, next)
	}
	tab := "login"
	if c.QueryParam("tab") == "register" {
		tab = "register"
	}
	return a.render(c, http.StatusOK, "login.html", pageData{Title: "Welcome to Avian", Tab: tab, Next: next})
}

func (a *application) formError(c echo.Context, tab, message string, status int) error {
	return a.render(c, status, "login.html", pageData{Title: "Welcome to Avian", Tab: tab,
		Next: safeNext(c.FormValue("next")), Email: c.FormValue("email"), Username: c.FormValue("username"), Error: message})
}

var usernamePattern = regexp.MustCompile(`^[a-z0-9_]{3,24}$`)

func (a *application) register(c echo.Context) error {
	if currentMember(c) != nil {
		return c.Redirect(http.StatusSeeOther, safeNext(c.FormValue("next")))
	}
	email := strings.ToLower(strings.TrimSpace(c.FormValue("email")))
	username := strings.ToLower(strings.TrimSpace(c.FormValue("username")))
	password := c.FormValue("password")
	address, err := mail.ParseAddress(email)
	if err != nil || address.Address != email || len(email) > 254 || !strings.Contains(email, "@") {
		return a.formError(c, "register", "Enter a valid email address.", http.StatusUnprocessableEntity)
	}
	if !usernamePattern.MatchString(username) {
		return a.formError(c, "register", "Use 3–24 letters, numbers, or underscores for your username.", http.StatusUnprocessableEntity)
	}
	if len(password) < 8 || len(password) > 72 {
		return a.formError(c, "register", "Choose a password between 8 and 72 bytes long.", http.StatusUnprocessableEntity)
	}
	if password != c.FormValue("confirm_password") {
		return a.formError(c, "register", "Your passwords do not match.", http.StatusUnprocessableEntity)
	}
	if err := a.store.Register(c.Request().Context(), email, username, password); err != nil {
		if errors.Is(err, errDuplicateAccount) {
			return a.formError(c, "register", err.Error(), http.StatusConflict)
		}
		return err
	}
	return a.signIn(c, email, password)
}

func (a *application) login(c echo.Context) error {
	if currentMember(c) != nil {
		return c.Redirect(http.StatusSeeOther, safeNext(c.FormValue("next")))
	}
	password := c.FormValue("password")
	if len(password) > 72 || password == "" {
		return a.formError(c, "login", "Email or password is incorrect.", http.StatusUnauthorized)
	}
	return a.signIn(c, strings.ToLower(strings.TrimSpace(c.FormValue("email"))), password)
}

func (a *application) signIn(c echo.Context, email, password string) error {
	id, err := a.store.Authenticate(c.Request().Context(), email, password)
	if errors.Is(err, sql.ErrNoRows) {
		return a.formError(c, "login", "Email or password is incorrect.", http.StatusUnauthorized)
	}
	if err != nil {
		return err
	}
	token, err := a.store.CreateSession(c.Request().Context(), id)
	if err != nil {
		return err
	}
	a.setCookie(c, sessionCookie, token, sessionLifetime)
	a.setCookie(c, csrfCookie, "", -time.Hour)
	return c.Redirect(http.StatusSeeOther, safeNext(c.FormValue("next")))
}

func (a *application) logout(c echo.Context) error {
	if cookie, err := c.Cookie(sessionCookie); err == nil {
		if err := a.store.DeleteSession(c.Request().Context(), cookie.Value); err != nil {
			return err
		}
	}
	a.setCookie(c, sessionCookie, "", -time.Hour)
	a.setCookie(c, csrfCookie, "", -time.Hour)
	return c.Redirect(http.StatusSeeOther, "/")
}

func (a *application) profile(c echo.Context) error {
	id, err := strconv.ParseInt(c.Param("id"), 10, 64)
	if err != nil || id < 1 {
		return echo.NewHTTPError(http.StatusNotFound, "This member could not be found.")
	}
	member, err := a.store.Member(c.Request().Context(), id)
	if errors.Is(err, sql.ErrNoRows) {
		return echo.NewHTTPError(http.StatusNotFound, "This member could not be found.")
	}
	if err != nil {
		return err
	}
	return a.render(c, http.StatusOK, "profile.html", pageData{Title: member.DisplayName, Profile: member})
}
